
import {
  useCallback,
  useEffect,
  useRef,
  useState,
} from "react";

import PianoKey from "./PianoKey.jsx";
import KeyboardGuide from "./KeyboardGuide.jsx";
import RecorderControls from "./RecorderControls.jsx";

import PolyphonicSynth from "../audio/PolyphonicSynth.js";
import Sequencer from "../sequencer/Sequencer.js";

import {
  PIANO_KEYS,
  WHITE_KEY_COUNT,
  BLACK_KEY_COUNT,
  TOTAL_PIANO_WIDTH,
} from "../utils/notes.js";

import {
  CODE_TO_MIDI,
  isTypingTarget,
} from "../utils/keyboardMapping.js";

const WHITE_KEYS = PIANO_KEYS.filter(
  (key) => !key.isBlack
);

const BLACK_KEYS = PIANO_KEYS.filter(
  (key) => key.isBlack
);

const NOTE_BY_MIDI = new Map(
  PIANO_KEYS.map((note) => [note.midi, note])
);

const MAX_VOICES = 8;

function Piano() {
  // Persistent audio and recording engines.
  const synthRef = useRef(null);
  const sequencerRef = useRef(null);

  // MIDI -> Set of input source identifiers.
  const noteOwnersRef = useRef(new Map());

  // Physical keyboard keys currently held.
  const pressedKeyboardCodesRef = useRef(new Set());

  // Piano UI state.
  const [selectedMidi, setSelectedMidi] = useState(null);

  const [activeNotes, setActiveNotes] = useState(
    () => new Set()
  );

  const [lastStolenMidi, setLastStolenMidi] = useState(null);

  // Recording and playback UI state.
  const [isRecording, setIsRecording] = useState(false);
  const [isPlaying, setIsPlaying] = useState(false);

  const [recordedEvents, setRecordedEvents] = useState([]);

  const [playbackSpeed, setPlaybackSpeed] = useState(1);

  // Initialize engine instances.
  // React 19 Strict Mode can repeat effect setup
  // and cleanup in development.
  useEffect(() => {
    const synth = new PolyphonicSynth(MAX_VOICES);
    const sequencer = new Sequencer();

    synthRef.current = synth;
    sequencerRef.current = sequencer;

    return () => {
      sequencer.dispose();
      synth.dispose();

      if (synthRef.current === synth) {
        synthRef.current = null;
      }

      if (sequencerRef.current === sequencer) {
        sequencerRef.current = null;
      }

      noteOwnersRef.current.clear();
      pressedKeyboardCodesRef.current.clear();
    };
  }, []);

  const handleSelectNote = useCallback((midi) => {
    setSelectedMidi(midi);
  }, []);

  const syncActiveNotes = useCallback(() => {
    const synth = synthRef.current;

    if (!synth) {
      return;
    }

    setActiveNotes(
      new Set(synth.getActiveMidiNotes())
    );
  }, []);

  // Start a note for one particular input source.
  const handleNoteOn = useCallback(
    (midi, frequency, sourceId) => {
      const synth = synthRef.current;
      const sequencer = sequencerRef.current;

      if (!synth || !sourceId) {
        return false;
      }

      if (!NOTE_BY_MIDI.has(midi)) {
        return false;
      }

      const ownersMap = noteOwnersRef.current;
      const existingOwners = ownersMap.get(midi);

      // A source cannot own the same note twice.
      if (existingOwners?.has(sourceId)) {
        return true;
      }

      // Another input already holds this note.
      // Add ownership without retriggering audio.
      if (existingOwners) {
        existingOwners.add(sourceId);
        return true;
      }

      // First owner: allocate an audio voice.
      const result = synth.noteOn(
        midi,
        frequency
      );

      if (!result.success) {
        return false;
      }

      // Close the recording of any stolen voice
      // before removing its ownership.
      if (result.stolenMidi !== null) {
        if (sequencer?.isRecording) {
          sequencer.recordNoteOff(
            result.stolenMidi
          );
        }

        ownersMap.delete(result.stolenMidi);

        setLastStolenMidi(result.stolenMidi);
      }

      ownersMap.set(
        midi,
        new Set([sourceId])
      );

      // Record manual note starts, but do not
      // record notes generated by playback.
      if (
        sequencer?.isRecording &&
        !sourceId.startsWith("playback:")
      ) {
        sequencer.recordNoteOn(
          midi,
          frequency
        );
      }

      syncActiveNotes();

      return true;
    },
    [syncActiveNotes]
  );

  // Remove one input source's ownership.
  const handleNoteOff = useCallback(
    (midi, sourceId) => {
      const ownersMap = noteOwnersRef.current;
      const owners = ownersMap.get(midi);

      if (!owners || !owners.has(sourceId)) {
        return;
      }

      owners.delete(sourceId);

      // Do not release audio while other
      // input sources still hold this note.
      if (owners.size > 0) {
        return;
      }

      ownersMap.delete(midi);

      const synth = synthRef.current;
      const sequencer = sequencerRef.current;

      // Record the actual end of a manual note.
      if (sequencer?.isRecording) {
        sequencer.recordNoteOff(midi);
      }

      if (synth) {
        synth.noteOff(midi);
      }

      syncActiveNotes();
    },
    [syncActiveNotes]
  );

  // Stop all audio and clear all input ownership.
  const handleStopAll = useCallback(() => {
    const synth = synthRef.current;
    const sequencer = sequencerRef.current;

    // Cancel scheduled playback, if any.
    sequencer?.stopPlayback();

    // Close recorded notes that are still active.
    if (sequencer?.isRecording) {
      for (const midi of noteOwnersRef.current.keys()) {
        sequencer.recordNoteOff(midi);
      }
    }

    synth?.stopAll();

    noteOwnersRef.current.clear();
    pressedKeyboardCodesRef.current.clear();

    setActiveNotes(new Set());
  }, []);

  // Physical computer keyboard support.
  useEffect(() => {
    const handleKeyDown = (event) => {
      const midi = CODE_TO_MIDI[event.code];

      if (midi === undefined) {
        return;
      }

      if (
        event.ctrlKey ||
        event.altKey ||
        event.metaKey
      ) {
        return;
      }

      if (isTypingTarget(event.target)) {
        return;
      }

      if (
        event.repeat ||
        pressedKeyboardCodesRef.current.has(
          event.code
        )
      ) {
        event.preventDefault();
        return;
      }

      const note = NOTE_BY_MIDI.get(midi);

      if (!note) {
        return;
      }

      event.preventDefault();

      pressedKeyboardCodesRef.current.add(
        event.code
      );

      const success = handleNoteOn(
        midi,
        note.frequency,
        `keyboard:${event.code}`
      );

      if (!success) {
        pressedKeyboardCodesRef.current.delete(
          event.code
        );

        return;
      }

      handleSelectNote(midi);
    };

    const handleKeyUp = (event) => {
      const midi = CODE_TO_MIDI[event.code];

      if (midi === undefined) {
        return;
      }

      if (
        !pressedKeyboardCodesRef.current.has(
          event.code
        )
      ) {
        return;
      }

      event.preventDefault();

      pressedKeyboardCodesRef.current.delete(
        event.code
      );

      handleNoteOff(
        midi,
        `keyboard:${event.code}`
      );
    };

    const releaseKeyboardNotes = () => {
      const pressedCodes = Array.from(
        pressedKeyboardCodesRef.current
      );

      pressedKeyboardCodesRef.current.clear();

      for (const code of pressedCodes) {
        const midi = CODE_TO_MIDI[code];

        if (midi !== undefined) {
          handleNoteOff(
            midi,
            `keyboard:${code}`
          );
        }
      }
    };

    const handleVisibilityChange = () => {
      if (document.hidden) {
        releaseKeyboardNotes();
      }
    };

    window.addEventListener(
      "keydown",
      handleKeyDown
    );

    window.addEventListener(
      "keyup",
      handleKeyUp
    );

    window.addEventListener(
      "blur",
      releaseKeyboardNotes
    );

    document.addEventListener(
      "visibilitychange",
      handleVisibilityChange
    );

    return () => {
      window.removeEventListener(
        "keydown",
        handleKeyDown
      );

      window.removeEventListener(
        "keyup",
        handleKeyUp
      );

      window.removeEventListener(
        "blur",
        releaseKeyboardNotes
      );

      document.removeEventListener(
        "visibilitychange",
        handleVisibilityChange
      );
    };
  }, [
    handleNoteOn,
    handleNoteOff,
    handleSelectNote,
  ]);

  // Start a new recording.
  const handleStartRecording = useCallback(() => {
    const sequencer = sequencerRef.current;

    if (!sequencer) {
      return;
    }

    const started = sequencer.startRecording();

    if (!started) {
      return;
    }

    setRecordedEvents([]);
    setIsRecording(true);
    setLastStolenMidi(null);
  }, []);

  // Finish recording and display the events.
  const handleStopRecording = useCallback(() => {
    const sequencer = sequencerRef.current;

    if (!sequencer) {
      return;
    }

    const events = sequencer.stopRecording();

    setRecordedEvents(events);
    setIsRecording(false);
  }, []);

  // Play the current recorded sequence.
  const handlePlay = useCallback(async () => {
    const sequencer = sequencerRef.current;

    if (
      !sequencer ||
      sequencer.isPlaying ||
      sequencer.isRecording
    ) {
      return;
    }

    if (sequencer.getEvents().length === 0) {
      return;
    }

    setIsPlaying(true);

    try {
      await sequencer.play({
        speed: playbackSpeed,

        onNoteOn: (
          midi,
          frequency,
          sourceId
        ) => {
          return handleNoteOn(
            midi,
            frequency,
            sourceId
          );
        },

        onNoteOff: (midi, sourceId) => {
          handleNoteOff(
            midi,
            sourceId
          );
        },
      });
    } catch (error) {
      console.error(
        "Sequencer playback failed:",
        error
      );
    } finally {
      // Do not update UI for a sequencer that
      // has already been replaced on unmount.
      if (sequencerRef.current === sequencer) {
        setIsPlaying(false);
      }
    }
  }, [
    playbackSpeed,
    handleNoteOn,
    handleNoteOff,
  ]);

  const handleStopPlayback = useCallback(() => {
    const sequencer = sequencerRef.current;

    sequencer?.stopPlayback();
  }, []);

  const handleClearRecording = useCallback(() => {
    const sequencer = sequencerRef.current;

    if (!sequencer) {
      return;
    }

    if (sequencer.clearRecording()) {
      setRecordedEvents([]);
    }
  }, []);

  const handleSpeedChange = useCallback((speed) => {
    setPlaybackSpeed(speed);
  }, []);

  // Read-only note information for display.
  const selectedNote =
    NOTE_BY_MIDI.get(selectedMidi) ?? null;

  const stolenNote =
    NOTE_BY_MIDI.get(lastStolenMidi) ?? null;

  const activeVoiceCount = activeNotes.size;

  return (
    <section className="piano-panel">
      {/* Piano header */}
      <div className="piano-panel__header">
        <div>
          <h2>88-Key Polyphonic Piano</h2>

          <p>
            Play using your physical keyboard,
            mouse, or touchscreen.
            Record and replay your music.
          </p>
        </div>

        <span className="piano-panel__status">
          Audio Enabled
        </span>
      </div>

      {/* Piano statistics */}
      <div className="piano-info">
        <div className="piano-info__item">
          <span>Total Keys</span>
          <strong>{PIANO_KEYS.length}</strong>
        </div>

        <div className="piano-info__item">
          <span>White Keys</span>
          <strong>{WHITE_KEY_COUNT}</strong>
        </div>

        <div className="piano-info__item">
          <span>Black Keys</span>
          <strong>{BLACK_KEY_COUNT}</strong>
        </div>

        <div className="piano-info__item">
          <span>Range</span>
          <strong>A0 – C8</strong>
        </div>
      </div>

      {/* Polyphonic voice engine */}
      <div className="voice-panel">
        <div className="voice-panel__header">
          <div>
            <h3>Polyphonic Voice Engine</h3>

            <p>
              FIFO voice stealing with an
              {` ${MAX_VOICES}`}-voice limit
            </p>
          </div>

          <button
            type="button"
            className="stop-all-button"
            onClick={handleStopAll}
            disabled={
              activeVoiceCount === 0 &&
              !isPlaying
            }
          >
            Stop All Notes
          </button>
        </div>

        <div className="voice-panel__stats">
          <div className="voice-stat">
            <span>Active Voices</span>

            <strong>
              {activeVoiceCount} / {MAX_VOICES}
            </strong>
          </div>

          <div className="voice-stat">
            <span>Available Voices</span>

            <strong>
              {MAX_VOICES - activeVoiceCount}
            </strong>
          </div>

          <div className="voice-stat">
            <span>Voice Stealing</span>

            <strong>
              {stolenNote
                ? `Last: ${stolenNote.noteName}`
                : "None"}
            </strong>
          </div>
        </div>

        <div
          className="voice-indicators"
          aria-label={`${activeVoiceCount} of ${MAX_VOICES} voices active`}
        >
          {Array.from(
            { length: MAX_VOICES },
            (_, index) => (
              <div
                key={index}
                className={
                  index < activeVoiceCount
                    ? "voice-indicator voice-indicator--active"
                    : "voice-indicator"
                }
                title={`Voice ${index + 1}`}
              />
            )
          )}
        </div>

        <div className="active-notes">
          <span>Currently Playing:</span>

          <div className="active-notes__list">
            {activeNotes.size > 0 ? (
              Array.from(activeNotes).map((midi) => {
                const note = NOTE_BY_MIDI.get(midi);

                return (
                  <span
                    className="active-note-badge"
                    key={midi}
                  >
                    {note?.noteName ?? midi}
                  </span>
                );
              })
            ) : (
              <span className="active-notes__empty">
                No active notes
              </span>
            )}
          </div>
        </div>
      </div>

      {/* Recording and playback */}
      <RecorderControls
        isRecording={isRecording}
        isPlaying={isPlaying}
        events={recordedEvents}
        playbackSpeed={playbackSpeed}
        onSpeedChange={handleSpeedChange}
        onStartRecording={handleStartRecording}
        onStopRecording={handleStopRecording}
        onPlay={handlePlay}
        onStopPlayback={handleStopPlayback}
        onClearRecording={handleClearRecording}
      />

      {/* Physical keyboard guide */}
      <KeyboardGuide activeNotes={activeNotes} />

      {/* Virtual piano */}
      <div
        className="piano-scroll"
        role="region"
        aria-label="Scrollable 88-key piano"
        tabIndex={0}
      >
        <div
          className="piano-keyboard"
          style={{
            width: TOTAL_PIANO_WIDTH,
          }}
        >
          <div className="white-keys">
            {WHITE_KEYS.map((key) => (
              <PianoKey
                key={key.midi}
                {...key}
                isSelected={
                  selectedMidi === key.midi
                }
                isPlaying={
                  activeNotes.has(key.midi)
                }
                onSelect={handleSelectNote}
                onNoteOn={handleNoteOn}
                onNoteOff={handleNoteOff}
              />
            ))}
          </div>

          <div className="black-keys">
            {BLACK_KEYS.map((key) => (
              <PianoKey
                key={key.midi}
                {...key}
                isSelected={
                  selectedMidi === key.midi
                }
                isPlaying={
                  activeNotes.has(key.midi)
                }
                onSelect={handleSelectNote}
                onNoteOn={handleNoteOn}
                onNoteOff={handleNoteOff}
              />
            ))}
          </div>
        </div>
      </div>

      <p className="piano-scroll-hint">
        Scroll to explore all 88 piano keys.
        Hold a key to play, then release to stop.
      </p>

      {/* Selected note */}
      <div className="selected-note-panel">
        <h3>Selected Note</h3>

        {selectedNote ? (
          <div className="selected-note-details">
            <div>
              <span>Note</span>
              <strong>
                {selectedNote.noteName}
              </strong>
            </div>

            <div>
              <span>MIDI Number</span>
              <strong>
                {selectedNote.midi}
              </strong>
            </div>

            <div>
              <span>Frequency</span>
              <strong>
                {selectedNote.frequency.toFixed(2)} Hz
              </strong>
            </div>

            <div>
              <span>Key Type</span>
              <strong>
                {selectedNote.isBlack
                  ? "Black"
                  : "White"}
              </strong>
            </div>
          </div>
        ) : (
          <p className="selected-note-empty">
            No key selected. Play a piano note
            to begin.
          </p>
        )}
      </div>
    </section>
  );
}

export default Piano;
